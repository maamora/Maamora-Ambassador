extension TrContext on BuildContext {
  /// Translates [key]. Replace placeholders with [args]:
  ///   context.tr('dash_days_left', args: {'n': 5})  // "5 days left"
  String tr(String key, {Map<String, Object> args = const {}}) {
    var text = AppStrings.of(Localizations.localeOf(this).languageCode, key);
    args.forEach((name, value) {
      text = text.replaceAll('{$name}', '$value');
    });
    return text;
  }
}
